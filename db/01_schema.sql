-- 成績管理システムのテーブル定義（DDL）
-- 対応する資料：データベース編 06 章（物理設計）、08 章（DDL）
-- 何度でも流し直せるよう、先に消してから作る（学習用。本番では絶対にしない）
--   psql -U postgres -d grades_db -f db/01_schema.sql

-- 子（参照する側）から先に消す
DROP TABLE IF EXISTS enrollments CASCADE;
DROP TABLE IF EXISTS courses     CASCADE;
DROP TABLE IF EXISTS students    CASCADE;
DROP TABLE IF EXISTS teachers    CASCADE;
DROP TABLE IF EXISTS departments CASCADE;

-- 親（参照される側）から先に作る
-- ① 学科
CREATE TABLE departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(50) NOT NULL UNIQUE
);

-- ② 教員
CREATE TABLE teachers (
    teacher_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(50) NOT NULL,
    department_id INTEGER     NOT NULL REFERENCES departments (department_id)
);

-- ② 学生
CREATE TABLE students (
    student_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(50) NOT NULL,
    department_id INTEGER     NOT NULL REFERENCES departments (department_id),
    enrolled_year SMALLINT    NOT NULL CHECK (enrolled_year >= 2000)
);

-- ③ 科目
CREATE TABLE courses (
    course_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(100) NOT NULL,
    credits    SMALLINT     NOT NULL CHECK (credits BETWEEN 1 AND 4),
    teacher_id INTEGER      NOT NULL REFERENCES teachers (teacher_id)
);

-- ④ 履修（学生と科目の多対多を解消したテーブル）
CREATE TABLE enrollments (
    enrollment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id    INTEGER  NOT NULL REFERENCES students (student_id) ON DELETE CASCADE,
    course_id     INTEGER  NOT NULL REFERENCES courses (course_id)   ON DELETE RESTRICT,
    academic_year SMALLINT NOT NULL,
    score         SMALLINT CHECK (score BETWEEN 0 AND 100),   -- NULL = 履修中
    UNIQUE (student_id, course_id, academic_year)             -- 二重履修の防止（要件 7）
);

-- 「科目 → 履修者」の検索用。外部キーには自動でインデックスが作られないため
CREATE INDEX idx_enrollments_course_id ON enrollments (course_id);
