package grades.domain;

import java.util.List;

/**
 * ある学生の履修をまとめたもの。
 * 「履修の集まり」に対する業務のルール（平均点の求め方）を、ここに置く。
 */
public record 履修一覧(List<履修> 履修リスト) {

    public 履修一覧 {
        履修リスト = List.copyOf(履修リスト);   // 受け取ったあとで、外から中身を変えられないようにする
    }

    /**
     * 平均点を計算する。
     * 平均は、点数のある履修だけで求める（履修中は含めない）。
     * 点数のある履修が 1 件もなければ 0.0。
     */
    public double 平均点を計算する() {
        int 合計 = 0;
        int 件数 = 0;
        for (履修 履修 : 履修リスト) {
            if (履修.履修中である()) {
                continue;                       // 履修中は数えない
            }
            合計 += 履修.点数();
            件数++;
        }
        if (件数 == 0) {
            return 0.0;
        }
        return (double) 合計 / 件数;
    }
}
